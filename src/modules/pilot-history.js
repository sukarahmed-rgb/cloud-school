/**
 * Adds the pilot lessons as private drafts. Safe to call twice.
 * @param {{books: any[], assignments: any[]}} data
 * @returns {boolean} true when something was added
 */
export function addPilotHistory(data) {
  const pilot = buildPilotHistory();
  let added = false;
  for (const b of pilot.books) {
    if (!data.books.some((x) => x.id === b.id)) {
      data.books.push(b);
      added = true;
    }
  }
  for (const a of pilot.assignments) {
    if (!data.assignments.some((x) => x.id === a.id)) {
      data.assignments.push(a);
      added = true;
    }
  }
  return added;
}
